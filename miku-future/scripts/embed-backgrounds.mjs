import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pluginDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inputs = {
  LIGHT_BACKGROUND_DATA_URL: {
    path: "assets/miku-future-light-background.png",
    mimeType: "image/png",
  },
  DARK_BACKGROUND_DATA_URL: {
    path: "assets/miku-future-dark-background.png",
    mimeType: "image/png",
  },
};

const exports = await Promise.all(
  Object.entries(inputs).map(async ([name, input]) => {
    const bytes = await readFile(resolve(pluginDirectory, input.path));
    return `export const ${name} = ${JSON.stringify(
      `data:${input.mimeType};base64,${bytes.toString("base64")}`,
    )};`;
  }),
);

const output = [
  "// Generated by scripts/embed-backgrounds.mjs. Do not edit by hand.",
  ...exports,
  "",
].join("\n");
await writeFile(resolve(pluginDirectory, "background-data.client.ts"), output, "utf8");
